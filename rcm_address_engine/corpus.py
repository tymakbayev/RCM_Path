"""Record corpus of the RCM Address Engine experiments (stand-alone copy of the author's JARVIS corpus generator).

The reference runs (A2-A8) generated their records with a2_gen.py, which imported this code from the author's JARVIS
memory-engine project: experiments/e19_cascade.py (build_corpus, resolve), experiments/e20_engine_cascade.py
(to_observations) and src/jarvis_mem/engine/model.py + deletion.py (record types, event and memory ids). The functions
below are copied from those files without changes to their logic; only the parts the generator uses are kept (the
compression cascade of E19, the engine of E20 and the zstandard dependency are not needed here).

Byte-for-byte equivalence with the reference runs is checked by `verify_corpus.py` against the sha256 of the
reference streams in results/data_manifest.sha256.

Copyright (c) 2026 Abu (github.com/tymakbayev). MIT License, see LICENSE.
"""

from __future__ import annotations

import random
import uuid
from dataclasses import dataclass
from enum import Enum

import numpy as np

# ================================================================ jarvis_mem/engine/model.py (types used by records)


class Retention(str, Enum):
    NORMAL = "NORMAL"
    EPHEMERAL = "EPHEMERAL"
    NO_STORE = "NO_STORE"


class Privacy(str, Enum):
    PUBLIC = "PUBLIC"
    PERSONAL = "PERSONAL"
    SENSITIVE = "SENSITIVE"
    SECRET = "SECRET"


class SourceKind(str, Enum):
    TOOL_VERIFIED = "tool_verified"
    OWNER = "owner"
    TRUSTED_SYSTEM = "trusted_system"
    INFERRED = "inferred"
    AGENT_SELF = "agent_self"
    UNTRUSTED = "untrusted"


class ValueKind(str, Enum):
    ENTITY = "entity"
    TEXT = "text"
    INT = "int"
    DECIMAL = "decimal"
    IP = "ip"
    UUID = "uuid"
    PATH = "path"
    COMMAND = "command"
    HASH = "hash"
    VERSION = "version"


@dataclass(frozen=True, slots=True)
class SourceRef:
    source_uuid: str
    kind: SourceKind
    independence_group: str
    trust: str = "trusted_user"


@dataclass(frozen=True, slots=True)
class TypedValue:
    kind: ValueKind
    raw: str  # canonical original form; exact values are never normalised


ASSERTED = "asserted"


@dataclass(frozen=True, slots=True)
class FactClaim:
    subject: str
    subject_type: str
    predicate: str
    value: TypedValue
    valid_from_us: int | None = None
    modality: str = ASSERTED
    confidence_q: int | None = None  # quantised confidence 0..255 (exact, no float round-trip)


@dataclass(frozen=True, slots=True)
class Observation:
    event_uuid: str
    device_id: str
    runtime_epoch: str
    device_seq: int
    observed_at_us: int
    source: SourceRef
    claims: tuple[FactClaim, ...]
    privacy: Privacy = Privacy.PERSONAL
    retention: Retention = Retention.NORMAL
    occurred_at_us: int | None = None


EVENT_NAMESPACE = uuid.UUID("0b8e4d5a-3c2f-4e71-9a6b-7d1e2f3a4b5c")


def derived_event_uuid(device_id: str, runtime_epoch: str, device_seq: int) -> str:
    """Event ids generated by the agent's own procedure (device, epoch, seq)."""
    return str(uuid.uuid5(EVENT_NAMESPACE, f"{device_id}|{runtime_epoch}|{device_seq}"))


# ================================================================ jarvis_mem/engine/deletion.py (memory id = record key)
MEMORY_NAMESPACE = uuid.UUID("6f1c2b8e-2d51-4b8a-9d8e-4a7a0c3e5f10")


def memory_id(event_uuid: str, claim_index: int) -> str:
    """Stable memory id of one claim: a function of its event id and position only."""
    return str(uuid.uuid5(MEMORY_NAMESPACE, f"{event_uuid}#{claim_index}"))


# ================================================================ experiments/e19_cascade.py (corpus of required atoms)
N_OBS = 50_000
MIX = {"rep": 0.25, "proc": 0.20, "conv": 0.25, "exact": 0.15, "temporal": 0.10, "noise": 0.05}
N_ENTITIES, N_PREDICATES, N_PHRASES = 3000, 120, 2000
T0 = 1_788_220_800_000  # 2026-09-01 in ms
DAY = 86_400_000
TIME_UNIT_MS = 1  # declared time precision of required atoms (1 = ms); a2_gen used 1
SYLL = ["ка", "ро", "ми", "та", "ле", "но", "св", "ер", "ал", "ия", "ор", "ан", "де", "ни", "ус", "ла", "ве", "ти"]


def build_corpus(seed: int, p_generated: float) -> tuple[list[tuple], dict, dict]:
    """Returns (atoms, dictionaries, generator_registry). Atom = (kind, subj, pred, vtag, value, vf, obs, src, conf, episode)."""
    rng = np.random.default_rng(seed)
    prng = random.Random(seed)
    names = [("".join(prng.choice(SYLL) for _ in range(prng.randint(2, 4))) + f"-{i}") for i in range(N_ENTITIES)]
    preds = [f"pred_{i}" for i in range(N_PREDICATES)]
    phrases = [" ".join("".join(prng.choice(SYLL) for _ in range(prng.randint(2, 3))) for _ in range(prng.randint(2, 5)))
               for _ in range(N_PHRASES)]
    ent_p = np.arange(1, N_ENTITIES + 1) ** -1.1
    ent_p /= ent_p.sum()
    ent_cdf = np.cumsum(ent_p)
    pred_p = np.arange(1, N_PREDICATES + 1) ** -1.0
    pred_p /= pred_p.sum()
    pred_cdf = np.cumsum(pred_p)
    phrase_p = np.arange(1, N_PHRASES + 1) ** -1.0
    phrase_p /= phrase_p.sum()
    phrase_cdf = np.cumsum(phrase_p)

    def draw(cdf: np.ndarray) -> int:
        return int(min(np.searchsorted(cdf, rng.random()), len(cdf) - 1))
    families = [{"pred": draw(pred_cdf), "who": [draw(ent_cdf) for _ in range(rng.integers(1, 3))],
                 "period": int(rng.integers(1, 12)) * 3_600_000, "mean_dur": int(rng.integers(5, 600))} for _ in range(40)]
    procs = [{"steps": int(rng.integers(3, 9)), "pred": int(rng.choice(N_PREDICATES))} for _ in range(30)]
    subnets = [f"10.0.{i}." for i in range(5)]
    dirs = ["/var/log/app", "/etc/nginx", "/home/user/projects/orion", "/opt/svc/bin", "/srv/data"]
    gen_counter = 0
    atoms: list[tuple] = []
    exact_values: list[tuple[int, object]] = []
    slots: list[tuple[int, int]] = []
    clock = {"rep": [T0] * len(families)}
    episode = 0
    counts = {k: int(v * N_OBS) for k, v in MIX.items()}
    order = [k for k, v in counts.items() for _ in range(v)]
    prng.shuffle(order)
    t_raw = T0
    for kind in order:
        t_raw += int(rng.exponential(30 * DAY / N_OBS))
        t = (t_raw // TIME_UNIT_MS) * TIME_UNIT_MS
        episode += 1
        delay = 0 if rng.random() < 0.8 else int(rng.integers(1, 600)) * 1000
        conf = int(rng.choice([15, 15, 15, 14, 12]))
        if kind == "noise":
            continue
        if kind == "rep":
            f = int(rng.integers(len(families)))
            fam = families[f]
            clock["rep"][f] += fam["period"] + int(rng.integers(-60, 61)) * 1000
            ts = clock["rep"][f]
            atoms.append(("EPISODE", fam["who"][0], fam["pred"], "ent", fam["who"][-1], ts, ts + delay, 1, conf, episode))
            atoms.append(("OUTCOME", fam["who"][0], fam["pred"], "int", 1 if rng.random() < 0.9 else 0, ts, ts + delay, 1, conf, episode))
            atoms.append(("DURATION", fam["who"][0], fam["pred"], "int", max(1, int(rng.normal(fam["mean_dur"], fam["mean_dur"] * 0.1))),
                          ts, ts + delay, 1, conf, episode))
        elif kind == "proc":
            p = int(rng.integers(len(procs)))
            service = int(rng.choice(40))
            atoms.append(("PROC_RUN", service, procs[p]["pred"], "int", p, t, t + delay, 2, conf, episode))
            for step in range(procs[p]["steps"]):
                code = 0 if rng.random() < 0.97 else int(rng.integers(1, 128))
                atoms.append(("STEP", service, step, "int", code, t, t + delay, 2, conf, episode))
            atoms.append(("VERIFY", service, procs[p]["pred"], "int", 1 if rng.random() < 0.95 else 0, t, t + delay, 2, conf, episode))
        elif kind == "conv":
            subj = draw(ent_cdf)
            pred = draw(pred_cdf)
            r = rng.random()
            if r < 0.6:
                vt, v = "ent", draw(ent_cdf)
            elif r < 0.85:
                vt, v = "str", phrases[draw(phrase_cdf)]
            else:
                vt, v = "int", int(rng.integers(0, 10_000))
            atoms.append(("FACT", subj, pred, vt, v, t, t + delay, 3, conf, episode))
            slots.append((subj, pred))
        elif kind == "exact":
            subj = draw(ent_cdf)
            if exact_values and rng.random() < 0.4:
                vt, v = exact_values[int(rng.integers(len(exact_values)))]
            else:
                vt = str(rng.choice(["ip", "uuid", "sha", "path", "cmd", "ver", "dec"]))
                if vt == "ip":
                    v = subnets[int(rng.integers(5))] + str(int(rng.integers(1, 255)))
                elif vt in ("uuid", "sha"):
                    if rng.random() < p_generated:
                        gen_counter += 1
                        v = ("GEN", vt, gen_counter)  # produced by the agent's own seeded procedure
                    else:
                        v = str(uuid.UUID(bytes=rng.bytes(16), version=4)) if vt == "uuid" else rng.bytes(32).hex()
                elif vt == "path":
                    v = f"{dirs[int(rng.integers(5))]}/{names[int(rng.integers(200))]}.{prng.choice(['log', 'conf', 'py', 'json'])}"
                elif vt == "cmd":
                    v = prng.choice(["systemctl restart ", "journalctl -u ", "ss -ltnp | grep ", "tail -n 200 "]) + names[int(rng.integers(100))]
                elif vt == "ver":
                    v = f"{rng.integers(0, 5)}.{rng.integers(0, 20)}.{rng.integers(0, 50)}"
                else:
                    v = f"{rng.integers(0, 10**6)}.{rng.integers(0, 100):02d}"
                exact_values.append((vt, v))
            atoms.append(("EXACT", subj, int(rng.integers(100, 120)), vt, v, t, t + delay, 4, conf, episode))
        elif kind == "temporal" and slots:
            subj, pred = slots[int(rng.integers(len(slots)))]
            atoms.append(("VERSION", subj, pred, "ent", draw(ent_cdf), t, t + delay, 3, conf, episode))
    return atoms, {"entities": names, "predicates": preds, "phrases": phrases}, {"families": families, "procs": procs}


def resolve(value: object, seed: int) -> object:
    """Generator capture: materialise a generated value from (kind, counter) with the agent's seeded procedure."""
    if isinstance(value, tuple) and value[0] == "GEN":
        _, vt, counter = value
        raw = random.Random(f"{seed}:{vt}:{counter}").getrandbits(256).to_bytes(32, "little")
        return str(uuid.UUID(bytes=raw[:16], version=4)) if vt == "uuid" else raw.hex()
    return value


# ================================================================ experiments/e20_engine_cascade.py (atoms -> observations)
SEED = 2026
VT_TO_KIND = {"ent": ValueKind.ENTITY, "int": ValueKind.INT, "str": ValueKind.TEXT, "ip": ValueKind.IP, "uuid": ValueKind.UUID,
              "sha": ValueKind.HASH, "path": ValueKind.PATH, "cmd": ValueKind.COMMAND, "ver": ValueKind.VERSION, "dec": ValueKind.DECIMAL}
SERVICE_KINDS = {"PROC_RUN", "STEP", "VERIFY"}


def to_observations(atoms: list[tuple], names: list[str]) -> list[Observation]:
    groups: dict[int, list[tuple]] = {}
    for a in atoms:
        groups.setdefault(a[9], []).append(a)
    out = []
    for ep in sorted(groups):
        group = groups[ep]
        head = group[0]
        claims = []
        for kind, subj, pred, vt, v, vf, _obs, _src, conf, _ep in group:
            subject = f"service-{subj}" if kind in SERVICE_KINDS else names[subj]
            if vt == "ent":
                raw = names[v]
            else:
                raw = str(resolve(v, SEED))
            claims.append(FactClaim(subject, "entity", f"{kind}:{pred}", TypedValue(VT_TO_KIND[vt], raw), vf * 1000, "asserted", conf))
        out.append(Observation(derived_event_uuid("agent", "e1", ep), "agent", "e1", ep, head[6] * 1000,
                               SourceRef(f"source-{head[7]}", SourceKind.OWNER, f"group-{head[7]}"), tuple(claims)))
    return out
